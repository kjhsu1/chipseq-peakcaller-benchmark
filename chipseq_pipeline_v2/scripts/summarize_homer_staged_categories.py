"""Summarize the current staged HOMER 128-run category results."""

"""Imports"""

import argparse
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Tuple

import pandas as pd

from scripts.category_summary_lib import parse_simple_yaml_map


"""Constants"""

EXPECTED_HOMER_STATS: List[Tuple[str, str]] = [
    ("flatearth_peak_narrow", "homer_tfclean_flatearth_peak_narrow_128_stats"),
    ("flatearth_plateau_broad", "homer_tfclean_flatearth_plateau_broad_128_stats"),
    ("wavy_peak_narrow", "homer_tfclean_realistic_peaks_wavy_narrow_128_stats"),
    ("hilly_peak_narrow", "homer_tfclean_realistic_peaks_hilly_narrow_128_stats"),
    ("wavy_plateau_broad", "homer_tfclean_realistic_plateaus_wavy_broad_128_stats"),
    ("hilly_plateau_broad", "homer_tfclean_realistic_plateaus_hilly_broad_128_stats"),
]


"""Functions"""


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Summarize completed staged HOMER category stats and record missing categories."
    )
    parser.add_argument(
        "--analysis-root",
        type=Path,
        default=Path("analysis_outputs"),
        help="Directory containing staged HOMER stats roots.",
    )
    parser.add_argument(
        "--name-map",
        type=Path,
        default=Path("configs/category_name_map.yaml"),
        help="Canonical category mapping file.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("analysis_outputs")
        / f"homer_staged_summary_{datetime.now().strftime('%Y%m%d')}",
        help="Directory to write staged HOMER summary outputs.",
    )
    return parser.parse_args()


def pick_best_f1_row(summary_df: pd.DataFrame) -> pd.Series:
    """Return the best F1 row, tie-broken toward lower control coverage."""
    ordered = summary_df.sort_values(["f1", "coverage_ctrl"], ascending=[False, True])
    return ordered.iloc[0]


def category_mode(label: str) -> str:
    """Return broad/narrow mode from the canonical label."""
    return "broad" if "broad" in label else "narrow"


def build_category_row(canonical_name: str, stats_dir: Path) -> Dict[str, object]:
    """Build one summary row from one completed category stats root."""
    summary_path = stats_dir / "group_summary_counts_based.csv"
    per_run_path = stats_dir / "per_run_stats.csv"
    summary_df = pd.read_csv(summary_path)
    per_run_df = pd.read_csv(per_run_path, dtype={"run_id": str})
    best_row = pick_best_f1_row(summary_df)
    return {
        "canonical_name": canonical_name,
        "mode": category_mode(canonical_name),
        "stats_dir": stats_dir.name,
        "results_dir": per_run_df.iloc[0]["planted_truth_path"].split("/")[0],
        "completed_runs": len(per_run_df),
        "best_f1": float(best_row["f1"]),
        "best_precision": float(best_row["precision"]),
        "best_recall": float(best_row["recall"]),
        "best_control_coverage": float(best_row["coverage_ctrl"]),
        "min_recall": float(summary_df["recall"].min()),
        "max_precision": float(summary_df["precision"].max()),
    }


def aggregate_mode_rows(category_df: pd.DataFrame) -> pd.DataFrame:
    """Aggregate headline staged behavior by broad/narrow mode."""
    rows: List[Dict[str, object]] = []
    for mode, group in category_df.groupby("mode"):
        rows.append(
            {
                "mode": mode,
                "completed_categories": int(len(group)),
                "mean_best_f1": float(group["best_f1"].mean()),
                "mean_best_precision": float(group["best_precision"].mean()),
                "mean_best_recall": float(group["best_recall"].mean()),
                "min_best_f1": float(group["best_f1"].min()),
                "max_best_f1": float(group["best_f1"].max()),
            }
        )
    return pd.DataFrame(rows).sort_values("mode")


def write_stage_status(
    output_dir: Path,
    analysis_root: Path,
    category_df: pd.DataFrame,
    missing_df: pd.DataFrame,
) -> None:
    """Write a compact staged-completeness manifest for the summary root."""
    lines = [
        f"analysis_root: {analysis_root}",
        f"completed_category_count: {len(category_df)}",
        f"missing_category_count: {len(missing_df)}",
        "completed_categories:",
    ]
    lines.extend(f"- {name}" for name in category_df["canonical_name"].tolist())
    lines.append("missing_categories:")
    lines.extend(f"- {name}" for name in missing_df["canonical_name"].tolist())
    lines.append("")
    lines.append("This manifest is generated by summarize_homer_staged_categories.py.")
    (output_dir / "stage_status.txt").write_text("\n".join(lines), encoding="utf-8")


def write_decision_summary(
    output_dir: Path, category_df: pd.DataFrame, mode_df: pd.DataFrame, missing_df: pd.DataFrame
) -> None:
    """Write a compact staged decision note from the current completed categories."""
    lines = [
        "# HOMER Staged Decision",
        "",
        f"- completed categories: `{len(category_df)}`",
        f"- missing categories: `{len(missing_df)}`",
        "",
    ]
    broad_df = mode_df[mode_df["mode"] == "broad"]
    narrow_df = mode_df[mode_df["mode"] == "narrow"]
    if not broad_df.empty and not narrow_df.empty:
        broad_row = broad_df.iloc[0]
        narrow_row = narrow_df.iloc[0]
        f1_gap = float(broad_row["mean_best_f1"] - narrow_row["mean_best_f1"])
        lines.extend(
            [
                "## Current Signal",
                (
                    f"- broad mean best F1: `{broad_row['mean_best_f1']:.4f}` "
                    f"across `{int(broad_row['completed_categories'])}` categories"
                ),
                (
                    f"- narrow mean best F1: `{narrow_row['mean_best_f1']:.4f}` "
                    f"across `{int(narrow_row['completed_categories'])}` categories"
                ),
                f"- broad-minus-narrow mean best F1 gap: `{f1_gap:.4f}`",
                "",
                "This is the mean of each completed category's best F1 across control-depth settings, not an average across all individual runs.",
                "",
                "## Decision Read",
                "- broad HOMER currently looks plausibly replacement-worthy",
                "- narrow HOMER is functional but still clearly weaker and recall-limited",
            ]
        )
        if not missing_df.empty:
            lines.extend(
                [
                    "",
                    "## Remaining Uncertainty",
                    "- this is still a partial staged verdict because the two hilly categories are missing",
                    "- the full six-category decision should be refreshed after those staged stats finish",
                ]
            )
    else:
        lines.extend(
            [
                "## Current Signal",
                "- insufficient completed categories to compare broad and narrow behavior yet",
            ]
        )
    (output_dir / "decision_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    """Write staged HOMER summary tables and a README."""
    args = parse_args()
    mapping = parse_simple_yaml_map(args.name_map)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    category_rows: List[Dict[str, object]] = []
    missing_rows: List[Dict[str, str]] = []

    for expected_label, stats_dir_name in EXPECTED_HOMER_STATS:
        canonical_name = mapping.get(stats_dir_name, expected_label)
        stats_dir = args.analysis_root / stats_dir_name
        if stats_dir.exists():
            category_rows.append(build_category_row(canonical_name, stats_dir))
        else:
            missing_rows.append(
                {
                    "canonical_name": canonical_name,
                    "expected_stats_dir": stats_dir_name,
                }
            )

    category_df = pd.DataFrame(category_rows).sort_values("canonical_name")
    missing_df = pd.DataFrame(
        missing_rows,
        columns=["canonical_name", "expected_stats_dir"],
    ).sort_values("canonical_name")
    mode_df = aggregate_mode_rows(category_df) if not category_df.empty else pd.DataFrame()

    category_df.to_csv(args.output_dir / "category_headlines.csv", index=False)
    missing_df.to_csv(args.output_dir / "missing_categories.csv", index=False)
    if not mode_df.empty:
        mode_df.to_csv(args.output_dir / "mode_headlines.csv", index=False)
    write_stage_status(args.output_dir, args.analysis_root, category_df, missing_df)
    write_decision_summary(args.output_dir, category_df, mode_df, missing_df)

    lines = [
        "# HOMER Staged Summary",
        "",
        f"- analysis root: `{args.analysis_root}`",
        f"- completed categories: `{len(category_df)}`",
        f"- missing categories: `{len(missing_df)}`",
        "",
        "## Completed Categories",
    ]
    for row in category_df.itertuples(index=False):
        lines.append(
            f"- `{row.canonical_name}`: best F1 `{row.best_f1:.4f}` at control `{row.best_control_coverage:g}` "
            f"(precision `{row.best_precision:.4f}`, recall `{row.best_recall:.4f}`)"
        )
    if category_df.empty:
        lines.append("- none")
    lines.extend(["", "## Missing Categories"])
    if missing_df.empty:
        lines.append("- none")
    else:
        for row in missing_df.itertuples(index=False):
            lines.append(
                f"- `{row.canonical_name}` expected at `{row.expected_stats_dir}`"
            )
    if not mode_df.empty:
        lines.extend(["", "## Mode Headlines"])
        for row in mode_df.itertuples(index=False):
            lines.append(
                f"- `{row.mode}`: mean of per-category best F1 `{row.mean_best_f1:.4f}` across `{row.completed_categories}` completed categories"
            )
        lines.extend(
            [
                "",
                "`mean of per-category best F1` means: find each category's best F1",
                "across control-depth settings, then average those category-best values.",
                "It is not the mean F1 across all individual runs.",
            ]
        )
    lines.extend(
        [
            "",
            "## Output Tables",
            "- `category_headlines.csv`",
            "- `missing_categories.csv`",
            "- `mode_headlines.csv`",
            "- `decision_summary.md`",
        ]
    )
    (args.output_dir / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


main()
